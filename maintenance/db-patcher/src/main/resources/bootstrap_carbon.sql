-- =====================================================================================
--  Multi-tenancy additions: the tenant table, then a nullable tenant_id column on every
--  tenant-aware table above. Table names are kept exactly as created above (no renames);
--  every tenant_id column is nullable so rows may be left without a tenant.
-- =====================================================================================

--changeset sharanya:create-srl_tenant
--preconditions onFail:MARK_RAN onError:HALT
--precondition-sql-check expectedResult:f select exists(select 1 from information_schema.tables where table_name='srl_tenant')
create table srl_tenant
(

    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tenant_name        VARCHAR(100)                            NOT NULL,
    tenant_type        BIGINT       NOT NULL,
    created_by         BIGINT,
    creation_time      TIMESTAMP WITHOUT TIME ZONE,
    last_modified_by   BIGINT,
    last_modified_time TIMESTAMP WITHOUT TIME ZONE,
    is_deleted         INTEGER,
    deleted_by         BIGINT,
    deleted_time       TIMESTAMP WITHOUT TIME ZONE,
    status             INTEGER,
    CONSTRAINT pk_srl_tenant PRIMARY KEY (id)
);

